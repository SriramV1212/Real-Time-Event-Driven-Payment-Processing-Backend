CREATE OR REPLACE FUNCTION post_ledger_transaction(
    p_payment_id TEXT,
    p_operation TEXT,
    p_entries JSONB,
    p_reverses_transaction_id BIGINT DEFAULT NULL
)
RETURNS BIGINT
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = pg_catalog, public, pg_temp
AS $$
DECLARE
    v_transaction_id BIGINT;
    v_original_transaction_id BIGINT;
    v_original_payment_id TEXT;
    v_entry RECORD;
    v_entries JSONB;
BEGIN
    IF p_operation IS NULL OR BTRIM(p_operation) = '' THEN
        RAISE EXCEPTION 'Operation cannot be empty';
    END IF;

    IF p_reverses_transaction_id IS NOT NULL THEN

        IF p_operation <> 'reversal' THEN
            RAISE EXCEPTION 'Reversal requires operation = reversal';
        END IF;

        IF p_entries IS NOT NULL THEN
            RAISE EXCEPTION 'Reversal entries must be generated by PostgreSQL';
        END IF;

        SELECT id, payment_id
        INTO v_original_transaction_id, v_original_payment_id
        FROM ledger_transactions
        WHERE id = p_reverses_transaction_id
          AND reverses_transaction_id IS NULL;

        IF v_original_transaction_id IS NULL THEN
            RAISE EXCEPTION 'Original transaction not found or is itself a reversal';
        END IF;

        IF p_payment_id IS DISTINCT FROM v_original_payment_id THEN
            RAISE EXCEPTION 'Reversal payment_id must match original transaction';
        END IF;

        SELECT jsonb_agg(
            jsonb_build_object(
                'account', a.name,
                'currency', le.currency,
                'direction',
                    CASE
                        WHEN le.direction = 'debit' THEN 'credit'
                        ELSE 'debit'
                    END,
                'amount_minor', le.amount_minor
            )
        )
        INTO v_entries
        FROM ledger_entries AS le
        JOIN ledger_accounts AS a ON a.id = le.account_id
        WHERE le.transaction_id = v_original_transaction_id;

        IF v_entries IS NULL THEN
            RAISE EXCEPTION 'Original transaction has no entries';
        END IF;

    ELSE

        IF p_operation = 'reversal' THEN
            RAISE EXCEPTION 'Reversal requires an original transaction ID';
        END IF;

        IF p_operation = 'payment_capture' AND p_payment_id IS NULL THEN
            RAISE EXCEPTION 'Payment capture requires a payment_id';
        END IF;

        IF p_entries IS NULL OR jsonb_typeof(p_entries) IS DISTINCT FROM 'array' THEN
            RAISE EXCEPTION 'Entries must be a JSON array';
        END IF;

        IF jsonb_array_length(p_entries) = 0 THEN
            RAISE EXCEPTION 'Entries cannot be empty';
        END IF;

        FOR v_entry IN
            SELECT value AS entry
            FROM jsonb_array_elements(p_entries)
        LOOP
            IF jsonb_typeof(v_entry.entry) IS DISTINCT FROM 'object' THEN
                RAISE EXCEPTION 'Invalid ledger entry structure';
            END IF;

            IF NOT (
                v_entry.entry ?& ARRAY[
                    'account', 'currency', 'direction', 'amount_minor'
                ]
            ) OR (
                SELECT COUNT(*)
                FROM jsonb_object_keys(v_entry.entry)
            ) <> 4 THEN
                RAISE EXCEPTION 'Invalid ledger entry structure';
            END IF;

            IF jsonb_typeof(v_entry.entry->'account') IS DISTINCT FROM 'string'
               OR NULLIF(BTRIM(v_entry.entry->>'account'), '') IS NULL
               OR v_entry.entry->>'currency' IS DISTINCT FROM 'USD'
               OR v_entry.entry->>'direction' NOT IN ('debit', 'credit')
               OR v_entry.entry->>'direction' IS NULL
               OR jsonb_typeof(v_entry.entry->'amount_minor') IS DISTINCT FROM 'number'
            THEN
                RAISE EXCEPTION 'Invalid ledger entry values';
            END IF;

            IF (v_entry.entry->>'amount_minor') !~ '^[0-9]+$' THEN
                RAISE EXCEPTION 'Amount must be a positive integer';
            END IF;

            IF (v_entry.entry->>'amount_minor')::NUMERIC < 1
               OR (v_entry.entry->>'amount_minor')::NUMERIC > 9223372036854775807
            THEN
                RAISE EXCEPTION 'Amount must be positive and fit in BIGINT';
            END IF;
        END LOOP;

        v_entries := p_entries;
    END IF;

    -- Check account existence and matching currency.
    IF EXISTS (
        SELECT 1
        FROM jsonb_array_elements(v_entries) AS e(entry)
        LEFT JOIN ledger_accounts AS a
            ON a.name = e.entry->>'account'
           AND a.currency = e.entry->>'currency'
        WHERE a.id IS NULL
    ) THEN
        RAISE EXCEPTION 'Ledger account does not exist or currency mismatch';
    END IF;

    -- Check debits equal credits for every currency.
    IF EXISTS (
        SELECT 1
        FROM jsonb_array_elements(v_entries) AS e(entry)
        GROUP BY e.entry->>'currency'
        HAVING
            SUM(
                CASE WHEN e.entry->>'direction' = 'debit'
                    THEN (e.entry->>'amount_minor')::NUMERIC
                    ELSE 0
                END
            )
            <>
            SUM(
                CASE WHEN e.entry->>'direction' = 'credit'
                    THEN (e.entry->>'amount_minor')::NUMERIC
                    ELSE 0
                END
            )
    ) THEN
        RAISE EXCEPTION 'Ledger transaction is unbalanced';
    END IF;

    -- Insert the accounting transaction.
    INSERT INTO ledger_transactions (
        payment_id,
        operation,
        reverses_transaction_id
    )
    VALUES (
        p_payment_id,
        p_operation,
        p_reverses_transaction_id
    )
    RETURNING id INTO v_transaction_id;

    -- Insert all accounting entries.
    INSERT INTO ledger_entries (
        transaction_id,
        account_id,
        direction,
        amount_minor,
        currency
    )
    SELECT
        v_transaction_id,
        a.id,
        e.entry->>'direction',
        (e.entry->>'amount_minor')::BIGINT,
        e.entry->>'currency'
    FROM jsonb_array_elements(v_entries) AS e(entry)
    JOIN ledger_accounts AS a
        ON a.name = e.entry->>'account'
       AND a.currency = e.entry->>'currency';

    -- Lock affected accounts in a consistent order.
    PERFORM id
    FROM ledger_accounts
    WHERE id IN (
        SELECT account_id
        FROM ledger_entries
        WHERE transaction_id = v_transaction_id
    )
    ORDER BY id
    FOR UPDATE;

    -- Update cached account balances.
    UPDATE ledger_accounts AS a
    SET balance_minor = a.balance_minor + changes.delta
    FROM (
        SELECT
            le.account_id,
            SUM(
                CASE
                    WHEN a2.type IN ('asset', 'expense') THEN
                        CASE
                            WHEN le.direction = 'debit'
                            THEN le.amount_minor::NUMERIC
                            ELSE -le.amount_minor::NUMERIC
                        END
                    WHEN a2.type = 'revenue' THEN
                        CASE
                            WHEN le.direction = 'credit'
                            THEN le.amount_minor::NUMERIC
                            ELSE -le.amount_minor::NUMERIC
                        END
                END
            ) AS delta
        FROM ledger_entries AS le
        JOIN ledger_accounts AS a2
            ON a2.id = le.account_id
        WHERE le.transaction_id = v_transaction_id
        GROUP BY le.account_id
    ) AS changes
    WHERE a.id = changes.account_id;

    RETURN v_transaction_id;
END;
$$;